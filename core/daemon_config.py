"""
SDDM Theme Manager - SDDM Daemon & Autologin Control Panel
Manages core SDDM daemon settings in /etc/sddm.conf.d/:
Autologin (User, Session, Relogin), NumLock on startup, Session detection, and user persistence.
"""

from pathlib import Path
from typing import Dict, List, Optional, Tuple

from .avatar_manager import AvatarManager
from .polkit import write_file_privileged


class DaemonConfigManager:
    """Manages SDDM daemon configuration options in /etc/sddm.conf.d/."""

    AUTOLOGIN_CONF = Path("/etc/sddm.conf.d/20-autologin.conf")
    GENERAL_CONF = Path("/etc/sddm.conf.d/00-general.conf")

    @classmethod
    def get_available_sessions(cls) -> List[Tuple[str, str]]:
        """
        Discovers installed Wayland and X11 sessions.
        Returns a list of tuples: (display_name, desktop_filename).
        """
        sessions: List[Tuple[str, str]] = []
        session_dirs = [
            Path("/usr/share/wayland-sessions"),
            Path("/usr/share/xsessions"),
        ]

        seen_files = set()
        for sdir in session_dirs:
            if sdir.exists():
                for desktop_file in sorted(sdir.glob("*.desktop")):
                    if desktop_file.name in seen_files:
                        continue
                    seen_files.add(desktop_file.name)
                    # Parse Name= from desktop file
                    name = desktop_file.stem.capitalize()
                    try:
                        content = desktop_file.read_text(encoding="utf-8", errors="ignore")
                        for line in content.splitlines():
                            if line.startswith("Name="):
                                name = line.split("=", 1)[1].strip()
                                break
                    except Exception:
                        pass
                    tag = " (Wayland)" if "wayland" in str(sdir) else " (X11)"
                    sessions.append((f"{name}{tag}", desktop_file.name))

        return sessions

    @classmethod
    def read_daemon_config(cls) -> Dict[str, any]:
        """
        Parses active autologin and general daemon settings from /etc/sddm.conf.d/.
        """
        config = {
            "autologin_enabled": False,
            "autologin_user": "",
            "autologin_session": "",
            "autologin_relogin": False,
            "numlock": "none",
            "remember_last_user": True,
            "remember_last_session": True,
        }

        # Check all conf files in /etc/sddm.conf.d/
        conf_d = Path("/etc/sddm.conf.d")
        conf_files = sorted(conf_d.glob("*.conf")) if conf_d.exists() else []
        if Path("/etc/sddm.conf").exists():
            conf_files.append(Path("/etc/sddm.conf"))

        for conf in conf_files:
            try:
                content = conf.read_text(encoding="utf-8", errors="ignore")
                section = ""
                for line in content.splitlines():
                    stripped = line.strip()
                    if stripped.startswith("[") and stripped.endswith("]"):
                        section = stripped[1:-1].lower()
                    elif "=" in stripped and not stripped.startswith("#"):
                        k, v = stripped.split("=", 1)
                        k = k.strip().lower()
                        v = v.strip()

                        if section == "autologin":
                            if k == "user" and v:
                                config["autologin_user"] = v
                                config["autologin_enabled"] = True
                            elif k == "session":
                                config["autologin_session"] = v
                            elif k == "relogin":
                                config["autologin_relogin"] = (v.lower() == "true")

                        elif section == "general":
                            if k == "numlock":
                                config["numlock"] = v.lower()

                        elif section == "users":
                            if k == "rememberlastuser":
                                config["remember_last_user"] = (v.lower() == "true")
                            elif k == "rememberlastsession":
                                config["remember_last_session"] = (v.lower() == "true")
            except Exception:
                continue

        return config

    @classmethod
    def save_daemon_config(cls, cfg: Dict[str, any]) -> Tuple[bool, str]:
        """
        Writes daemon settings to /etc/sddm.conf.d/20-autologin.conf and 00-general.conf.
        """
        # 1. Autologin config
        if cfg.get("autologin_enabled", False) and cfg.get("autologin_user"):
            auto_lines = [
                "# Autologin configuration generated by SDDM Theme Manager",
                "[Autologin]",
                f"User={cfg['autologin_user']}",
            ]
            if cfg.get("autologin_session"):
                auto_lines.append(f"Session={cfg['autologin_session']}")
            auto_lines.append(f"Relogin={'true' if cfg.get('autologin_relogin', False) else 'false'}")
            auto_content = "\n".join(auto_lines) + "\n"
            ok, msg = write_file_privileged(cls.AUTOLOGIN_CONF, auto_content)
            if not ok:
                return False, f"Failed to save autologin settings: {msg}"
        else:
            # If disabled, explicitly clear autologin in drop-in config to override any fallbacks
            auto_lines = [
                "# Autologin disabled by SDDM Theme Manager",
                "[Autologin]",
                "User=",
                "Session=",
                "Relogin=false",
            ]
            auto_content = "\n".join(auto_lines) + "\n"
            write_file_privileged(cls.AUTOLOGIN_CONF, auto_content)

        # 2. General and Users config
        gen_lines = [
            "# General SDDM configuration generated by SDDM Theme Manager",
            "[General]",
            f"Numlock={cfg.get('numlock', 'none')}",
            "",
            "[Users]",
            f"RememberLastUser={'true' if cfg.get('remember_last_user', True) else 'false'}",
            f"RememberLastSession={'true' if cfg.get('remember_last_session', True) else 'false'}",
        ]
        gen_content = "\n".join(gen_lines) + "\n"
        ok, msg = write_file_privileged(cls.GENERAL_CONF, gen_content)
        if not ok:
            return False, f"Failed to save general daemon settings: {msg}"

        return True, "SDDM daemon settings applied successfully!"
